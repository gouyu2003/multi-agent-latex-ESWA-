"""Generate project-only Biber maps; reject drift in the original database."""
from pathlib import Path
import hashlib,json
ROOT=Path(__file__).resolve().parents[1]
data=json.loads((ROOT/'apa_reference_adaptations.json').read_text(encoding='utf-8'))
assert hashlib.sha256((ROOT/'references.bib').read_bytes()).hexdigest()==data['references_sha256'],'Original database changed: review adaptations first'
lines=['% Generated by tools/generate_apa_sourcemap.py from the reviewed overlay.', '% Original references.bib and official CAS/style files remain unchanged.', r'\DeclareSourcemap{',r'  \maps[datatype=bibtex]{']
for r in data['records']:
 if r['target_type']==r['original_type'] and not r['updates']:continue
 lines += [r'    \map[overwrite]{',r'      \step[fieldsource=entrykey, match=\regexp{^'+r['key']+r'$}, final]']
 if r['target_type']!=r['original_type']:lines.append(r'      \step[typesource='+r['original_type']+', typetarget='+r['target_type']+']')
 for f,v in r['updates'].items():
  # keyval unwraps fully grouped values. Expand detokenize only after key parsing,
  # preserving literal BibTeX braces in the XML (and hence corporate names).
  lines.append(r'      \step[fieldset='+f+(', null]' if v is None else r', fieldvalue={\detokenize{'+v+'}}]'))
 lines.append('    }')
lines += ['  }','}']
(ROOT/'eswa-apa-sourcemap.tex').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Generated project maps:',len(data['records']))
